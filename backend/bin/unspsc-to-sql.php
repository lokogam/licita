<?php

/**
 * Generates bd/02_activities.sql from the UNSPSC Spanish classifier spreadsheet.
 *
 * Usage: php bin/unspsc-to-sql.php <path/to/unspsc.xlsx> [output.sql]
 * Source: https://a.storyblok.com/f/167454/x/8db69f44cd/unspcs-clasificador-de-bienes-y-servicios-de-naciones-unidas-en-espanol.xlsx
 */

declare(strict_types=1);

use App\Support\Unspsc\ActivitiesSqlWriter;
use App\Support\Unspsc\UnspscRowParser;
use PhpOffice\PhpSpreadsheet\IOFactory;

require __DIR__ . '/../vendor/autoload.php';

ini_set('memory_limit', '2G');

$source = $argv[1] ?? null;
$target = $argv[2] ?? __DIR__ . '/../../bd/02_activities.sql';

if ($source === null || !is_file($source)) {
    fwrite(STDERR, "Usage: php bin/unspsc-to-sql.php <path/to/unspsc.xlsx> [output.sql]\n");
    exit(1);
}

$reader = IOFactory::createReader('Xlsx');
$reader->setReadDataOnly(true);
$sheet = $reader->load($source)->getSheet(0);

$parser = new UnspscRowParser();
$activities = (static function () use ($sheet, $parser): Generator {
    foreach ($sheet->toArray(null, false, false, false) as $row) {
        $activity = $parser->parse($row);
        if ($activity !== null) {
            yield $activity;
        }
    }
})();

$stream = fopen($target, 'wb');
if ($stream === false) {
    fwrite(STDERR, "Unable to write {$target}\n");
    exit(1);
}

fwrite($stream, "-- UNSPSC goods and services classifier (Spanish) - generated by backend/bin/unspsc-to-sql.php\n");
$count = (new ActivitiesSqlWriter())->write($activities, $stream);
fclose($stream);

fwrite(STDOUT, "Wrote {$count} activities to {$target}\n");
